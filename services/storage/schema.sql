-- DuckDB schema for AI Sales Intelligence Platform
-- Three main tables: staging_records (raw), accounts (aggregated), account_top_records (index)

CREATE TABLE IF NOT EXISTS staging_records (
    record_id           BIGINT PRIMARY KEY,
    ip                   VARCHAR,
    port                 INTEGER,
    transport            VARCHAR,
    root_domain          VARCHAR,
    hostnames            VARCHAR[],
    domains              VARCHAR[],
    org                  VARCHAR,
    isp                  VARCHAR,
    asn                  VARCHAR,
    country_code         VARCHAR,
    region               VARCHAR,
    city                 VARCHAR,
    latitude             DOUBLE,
    longitude            DOUBLE,
    ts                   TIMESTAMP,
    product              VARCHAR,
    version              VARCHAR,
    os                   VARCHAR,
    device               VARCHAR,
    devicetype           VARCHAR,
    cpe                  VARCHAR[],
    tags                 VARCHAR[],
    is_infra_noise       BOOLEAN,
    has_vulns            BOOLEAN,
    vuln_count           INTEGER,
    max_cvss             DOUBLE,
    max_epss             DOUBLE,
    vuln_ids             VARCHAR[],
    has_ssl              BOOLEAN,
    ssl_self_signed      BOOLEAN,
    ssl_version_weak     BOOLEAN,
    ssl_jarm             VARCHAR,
    http_title           VARCHAR,
    http_server          VARCHAR,
    http_status          INTEGER,
    has_securitytxt      BOOLEAN,
    is_database_port     BOOLEAN,
    is_legacy_protocol   BOOLEAN,
    is_iot_ot_device     BOOLEAN,
    is_eol_product       BOOLEAN,
    is_honeypot          BOOLEAN,
    data_snippet         VARCHAR,
    shodan_module        VARCHAR,
    ingested_at          TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS accounts (
    root_domain             VARCHAR PRIMARY KEY,
    record_count            INTEGER,
    asset_count              INTEGER,
    distinct_ips             INTEGER,
    distinct_ports           INTEGER,
    port_list                VARCHAR[],
    countries                VARCHAR[],
    primary_country_code     VARCHAR,
    primary_org              VARCHAR,
    cloud_or_cdn_fronted      BOOLEAN,
    vuln_count_total          INTEGER,
    vuln_count_critical       INTEGER,
    max_cvss                  DOUBLE,
    max_epss                  DOUBLE,
    top_cve_ids                VARCHAR[],
    exposed_database_count     INTEGER,
    legacy_protocol_count       INTEGER,
    weak_tls_count               INTEGER,
    self_signed_cert_count        INTEGER,
    eol_product_count              INTEGER,
    iot_ot_device_count             INTEGER,
    honeypot_flagged                 BOOLEAN,
    excluded_as_honeypot               BOOLEAN DEFAULT false,
    sample_http_titles                  VARCHAR[],
    sample_products                       VARCHAR[],
    first_seen                             TIMESTAMP,
    last_seen                               TIMESTAMP,
    snapshot_date                            VARCHAR,
    risk_score                                DOUBLE,
    score_version                              VARCHAR,
    signal_tags                                 VARCHAR[],
    score_explanation                            VARCHAR,
    scored_at                                     TIMESTAMP,
    inferred_company_name                          VARCHAR,
    inferred_industry                               VARCHAR,
    narrative                                        VARCHAR,
    outreach_draft                                    VARCHAR,
    enriched_at                                        TIMESTAMP
);

CREATE TABLE IF NOT EXISTS account_top_records (
    root_domain   VARCHAR,
    record_id     BIGINT,
    rank          INTEGER,
    PRIMARY KEY (root_domain, record_id)
);
